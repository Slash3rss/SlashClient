	/** Each case's rewards: name as the window writes it → item id, in the window's order. */
	static Map<String, Map<String, String>> all() {
		Map<String, Map<String, String>> out = new LinkedHashMap<>();
		for (String[] pool : POOLS) {
			Map<String, String> rewards = new LinkedHashMap<>();
			for (int i = 1; i < pool.length; i++) {
				int bar = pool[i].indexOf('|');
				rewards.put(pool[i].substring(bar + 1), pool[i].substring(0, bar));
			}
			out.put(pool[0], rewards);
		}
		return out;
	}
